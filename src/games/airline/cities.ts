/** 두 도시 사이 거리 (km, 대권 거리) */
export function distanceKm(a: CityDef, b: CityDef): number {
  const R = 6371;
  const toRad = Math.PI / 180;
  const dLat = (b.lat - a.lat) * toRad;
  const dLon = (b.lon - a.lon) * toRad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * toRad) * Math.cos(b.lat * toRad) * Math.sin(dLon / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.min(1, Math.sqrt(h))));
}

/** 도시 id → 번호 */
export const CITY_INDEX: Record<string, number> = Object.fromEntries(CITIES.map((c, i) => [c.id, i]));

const N = CITIES.length;
const DIST = new Float64Array(N * N);
for (let i = 0; i < N; i++) for (let j = 0; j < N; j++) DIST[i * N + j] = i === j ? 0 : distanceKm(CITIES[i], CITIES[j]);

/** 도시 id 둘로 거리 (미리 셈해 둔 표) */
export function dist(a: string, b: string): number {
  return DIST[CITY_INDEX[a] * N + CITY_INDEX[b]];
}

/** 두 도시를 늘 같은 순서로 묶은 번호 (빠른 열쇠) */
export function pairIndex(a: string, b: string): number {
  const i = CITY_INDEX[a];
  const j = CITY_INDEX[b];
  return i < j ? i * N + j : j * N + i;
}

/** 두 도시를 늘 같은 순서로 묶은 열쇠 */
export function pairKey(a: string, b: string): string {
  return a < b ? `${a}|${b}` : `${b}|${a}`;
}
