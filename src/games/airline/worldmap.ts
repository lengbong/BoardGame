/**
 * 직접 그린 단순한 세계 지도. 대륙 해안선은 실제 지형을 아주 거칠게 따라 찍은 점([경도, 위도])이다.
 * 태평양이 가운데 오도록 경도 −25°(대서양 한가운데)를 지도의 양쪽 끝으로 삼고,
 * 높은 위도가 조금 커 보이는 밀러 도법으로 위도를 펴서 1080 × 477 크기로 그린다.
 */
export const SEAM = -25;
export const MAP_SCALE = 3;
export const MAP_W = 360 * MAP_SCALE;
const LAT_TOP = 76;
const LAT_BOTTOM = -56;

function miller(lat: number): number {
  const phi = (lat * Math.PI) / 180;
  return (1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * phi)) * 180) / Math.PI;
}

const Y_TOP = miller(LAT_TOP);
export const MAP_H = Math.round((Y_TOP - miller(LAT_BOTTOM)) * MAP_SCALE);

/** 경도·위도 → 지도 좌표 (x는 0 이상 MAP_W 미만) */
export function project(lon: number, lat: number): { x: number; y: number } {
  const x = ((((lon - SEAM) % 360) + 360) % 360) * MAP_SCALE;
  const y = (Y_TOP - miller(Math.max(LAT_BOTTOM - 4, Math.min(LAT_TOP + 8, lat)))) * MAP_SCALE;
  return { x, y };
}

