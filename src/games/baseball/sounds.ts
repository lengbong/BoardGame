import { burst, sfx, tone } from '../../lib/sound';

/** 숫자야구 효과음 (모두 합성음) */
export const bbSound = {
  /** 숫자 단추 */
  key() {
    tone(880, 0, 0.04, 'triangle', 0.05);
  },
  /** 지우기 */
  erase() {
    tone(520, 0, 0.05, 'triangle', 0.05, 360);
  },
  /** 같은 숫자를 또 누르는 등 안 되는 입력 */
  error() {
    tone(196, 0, 0.12, 'square', 0.04);
    tone(174, 0.1, 0.16, 'square', 0.04);
  },
  /** 메모 표시 */
  note() {
    tone(1320, 0, 0.03, 'sine', 0.04);
  },
  /** 비밀 숫자를 정했을 때: 철컥 */
  lock() {
    burst(0, 0.04, 3200, 2, 0.2);
    tone(330, 0.03, 0.08, 'square', 0.04);
    tone(660, 0.1, 0.14, 'triangle', 0.08);
  },
  /** 공이 날아가는 소리 */
  pitch() {
    burst(0, 0.32, 600, 1.2, 0.12, 2800);
  },
  /** 방망이에 딱! */
  bat() {
    burst(0, 0.035, 3800, 1.5, 0.45);
    tone(1500, 0, 0.05, 'square', 0.05, 900);
    tone(220, 0, 0.06, 'triangle', 0.12, 140);
  },
  /** 헛스윙 후 포수 글러브에 퍽 */
  mitt() {
    burst(0, 0.05, 420, 1.4, 0.4);
    tone(110, 0, 0.08, 'sine', 0.2, 70);
  },
  /** 전광판 스트라이크 불 */
  strikeLamp(i = 0) {
    tone(988 + i * 60, 0, 0.12, 'triangle', 0.1);
  },
  /** 전광판 볼 불 */
  ballLamp(i = 0) {
    tone(587 + i * 40, 0, 0.12, 'sine', 0.11);
  },
  /** 아웃: 삐익- */
  out() {
    tone(660, 0, 0.12, 'square', 0.045);
    tone(440, 0.13, 0.3, 'square', 0.045, 330);
  },
  /** 홈런: 딱! 하고 관중 함성과 팡파르 */
  homerun() {
    bbSound.bat();
    burst(0.05, 1.6, 900, 0.6, 0.22, 1400);
    burst(0.15, 1.4, 1800, 0.8, 0.12, 2400);
    [523, 659, 784, 1047, 784, 1047].forEach((f, i) => tone(f, 0.35 + i * 0.11, i === 5 ? 0.5 : 0.14, 'square', 0.05));
  },
  /** 마지막 기회: 둥둥둥 북소리 */
  lastChance() {
    for (let i = 0; i < 6; i++) tone(98, i * 0.09, 0.08, 'sine', 0.25, 70);
    tone(784, 0.6, 0.3, 'triangle', 0.08);
  },
  win() {
    sfx.win();
  },
  /** 무승부·답 보기 */
  draw() {
    tone(523, 0, 0.15, 'triangle', 0.1);
    tone(523, 0.18, 0.3, 'triangle', 0.1);
  },
};
