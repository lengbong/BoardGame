/** 점들을 이어 지도 좌표로 (경도 360°를 넘어가도 끊기지 않게 펴 준다) */
export function unwrapPoints(pts: readonly Pt[]): { x: number; y: number }[] {
  const out: { x: number; y: number }[] = [];
  let prev: number | null = null;
  for (const [lon, lat] of pts) {
    const p = project(lon, lat);
    let x = p.x;
    if (prev !== null) {
      while (x - prev > MAP_W / 2) x -= MAP_W;
      while (x - prev < -MAP_W / 2) x += MAP_W;
    }
    out.push({ x, y: p.y });
    prev = x;
  }
  return out;
}

/** 모양 하나의 SVG path. 지도 끝을 넘으면 반대쪽에 한 번 더 그린다 */
export function shapePath(pts: readonly Pt[]): string {
  const p = unwrapPoints(pts);
  const minX = Math.min(...p.map((v) => v.x));
  const maxX = Math.max(...p.map((v) => v.x));
  const shifts = [0];
  if (maxX > MAP_W) shifts.push(-MAP_W);
  if (minX < 0) shifts.push(MAP_W);
  return shifts.map((dx) => `M${p.map((v) => `${(v.x + dx).toFixed(1)} ${v.y.toFixed(1)}`).join('L')}Z`).join('');
}

/** 점이 모양 안에 있는지 (지도 좌표) */
export function insideShape(x: number, y: number, pts: readonly Pt[]): boolean {
  const p = unwrapPoints(pts);
  let inside = false;
  for (const dx of [0, -MAP_W, MAP_W]) {
    for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
      const xi = p[i].x + dx;
      const yi = p[i].y;
      const xj = p[j].x + dx;
      const yj = p[j].y;
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
    if (inside) return true;
  }
  return inside;
}

/** 점에서 모양 테두리까지 가장 가까운 거리 (지도 좌표) */
export function distanceToShape(x: number, y: number, pts: readonly Pt[]): number {
  const p = unwrapPoints(pts);
  let best = Infinity;
  for (const dx of [0, -MAP_W, MAP_W]) {
    for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
      const ax = p[j].x + dx;
      const ay = p[j].y;
      const bx = p[i].x + dx;
      const by = p[i].y;
      const lx = bx - ax;
      const ly = by - ay;
      const t = Math.max(0, Math.min(1, ((x - ax) * lx + (y - ay) * ly) / (lx * lx + ly * ly || 1)));
      best = Math.min(best, Math.hypot(x - (ax + t * lx), y - (ay + t * ly)));
    }
  }
  return best;
}


export interface RouteArc {
  /** 지도에 그릴 경로 (지도 끝을 넘으면 반대쪽에 한 벌 더) */
  copies: string[];
  /** 모든 벌을 이은 경로 (선·누르는 자리) */
  d: string;
  /** 가운데 점 (지도 안쪽 좌표) */
  mid: { x: number; y: number };
  /** 지도 끝을 넘는지 */
  wraps: boolean;
}

/**
 * 두 도시를 잇는 대권 항로 (지구 위 가장 짧은 길)를 점으로 찍어 그린다.
 * 지도 끝을 넘으면 x를 이어서 셈하고, 반대쪽에 같은 선을 한 벌 더 그려 끊김 없이 보이게 한다.
 * lane: 같은 두 도시를 여러 회사가 날 때 옆으로 조금씩 비키는 칸 (… −1, 0, 1 …)
 */
export function greatCircleArc(a: { lon: number; lat: number }, b: { lon: number; lat: number }, lane = 0): RouteArc {
  const rad = Math.PI / 180;
  const toVec = (lon: number, lat: number) => [Math.cos(lat * rad) * Math.cos(lon * rad), Math.cos(lat * rad) * Math.sin(lon * rad), Math.sin(lat * rad)];
  const va = toVec(a.lon, a.lat);
  const vb = toVec(b.lon, b.lat);
  const dot = Math.max(-1, Math.min(1, va[0] * vb[0] + va[1] * vb[1] + va[2] * vb[2]));
  const omega = Math.acos(dot);
  const n = Math.max(8, Math.min(48, Math.round(omega / (3 * rad))));
  const pts: { x: number; y: number }[] = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    let v: number[];
    if (omega < 1e-6) v = va;
    else {
      const s1 = Math.sin((1 - t) * omega) / Math.sin(omega);
      const s2 = Math.sin(t * omega) / Math.sin(omega);
      v = [s1 * va[0] + s2 * vb[0], s1 * va[1] + s2 * vb[1], s1 * va[2] + s2 * vb[2]];
    }
    const lat = Math.atan2(v[2], Math.hypot(v[0], v[1])) / rad;
    const lon = Math.atan2(v[1], v[0]) / rad;
    const p = project(lon, lat);
    // 앞 점과 이어지게 x를 펼친다
    if (pts.length) {
      const prev = pts[pts.length - 1].x;
      while (p.x - prev > MAP_W / 2) p.x -= MAP_W;
      while (p.x - prev < -MAP_W / 2) p.x += MAP_W;
    }
    pts.push(p);
  }
  // 짧은 노선은 대권이 거의 곧아서 겹치기 쉬우니 살짝 휘게 하고, 회사마다 옆으로 비킨다
  const first = pts[0];
  const last = pts[pts.length - 1];
  const dx = last.x - first.x;
  const dy = last.y - first.y;
  const len = Math.hypot(dx, dy) || 1;
  const nx = dy / len;
  const ny = -dx / len;
  const bend = Math.min(18, len * 0.08);
  const side = ny <= 0 ? 1 : -1;
  const shifted = pts.map((p, i) => {
    const t = i / n;
    const hump = 4 * t * (1 - t);
    const off = (bend * side + lane * 3.2) * hump;
    return { x: p.x + nx * off, y: p.y + ny * off };
  });
  const minX = Math.min(...shifted.map((p) => p.x));
  const maxX = Math.max(...shifted.map((p) => p.x));
  const line = (shift: number) => shifted.map((p, i) => `${i ? 'L' : 'M'}${(p.x + shift).toFixed(1)} ${p.y.toFixed(1)}`).join('');
  const copies = [line(0)];
  if (minX < 0) copies.push(line(MAP_W));
  if (maxX > MAP_W) copies.push(line(-MAP_W));
  const m = shifted[Math.floor(shifted.length / 2)];
  return { copies, d: copies.join(''), mid: { x: ((m.x % MAP_W) + MAP_W) % MAP_W, y: m.y }, wraps: copies.length > 1 };
}
