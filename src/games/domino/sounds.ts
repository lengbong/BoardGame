import { burst, tone } from '../../lib/sound';

/** 도미노 효과음 (모두 합성음, 효과음 끄기를 따른다) */
export const dominoSfx = {
  /** 패를 탁자에 탁 내려놓는 나무 소리 */
  clack() {
    burst(0, 0.03, 3400, 2.2, 0.42);
    tone(380, 0, 0.06, 'triangle', 0.13, 230);
    burst(0.012, 0.05, 1200, 3, 0.18);
    // 옆 패에 살짝 부딪히는 소리
    burst(0.07, 0.025, 2800, 3, 0.14);
    tone(520, 0.07, 0.03, 'triangle', 0.05, 400);
  },
  /** 뽑는 더미에서 패를 스르륵 끌어오는 소리 */
  draw() {
    burst(0, 0.14, 650, 1.1, 0.13, 2000);
    burst(0.13, 0.025, 3000, 3, 0.16);
    tone(300, 0.13, 0.04, 'triangle', 0.06, 220);
  },
  /** 통과: 탁자를 똑똑 두드리는 소리 */
  pass() {
    for (const t of [0, 0.17]) {
      burst(t, 0.07, 240, 2.4, 0.55);
      tone(150, t, 0.09, 'sine', 0.18, 85);
    }
  },
  /** 패를 섞을 때 (탁자 위에서 패를 휘젓는 소리) */
  wash() {
    for (let i = 0; i < 16; i++) {
      const t = i * 0.045 + Math.random() * 0.02;
      burst(t, 0.028, 2200 + Math.random() * 1800, 3, 0.2);
      if (i % 3 === 0) tone(330 + Math.random() * 120, t, 0.03, 'triangle', 0.05, 220);
    }
  },
  /** 패를 고르거나 끝을 고를 때 */
  select() {
    tone(1250, 0, 0.04, 'sine', 0.05, 1500);
  },
  /** 한 판 이겼을 때 (마림바풍 오름 화음) */
  roundWin() {
    [587, 740, 880, 1175].forEach((f, i) => tone(f, i * 0.09, 0.24, 'triangle', 0.12));
    tone(1480, 0.38, 0.45, 'sine', 0.06);
    burst(0.38, 0.05, 3000, 2, 0.12);
  },
  /** 아무도 낼 수 없어서 막혔을 때 */
  blocked() {
    [523, 494, 440].forEach((f, i) => tone(f, i * 0.15, 0.22, 'triangle', 0.08));
    burst(0.46, 0.08, 260, 2, 0.32);
  },
};
